/// Display name of the service usually found on `port`.
pub fn service_name(port: u16) -> Option<&'static str> {
    SERVICES
        .binary_search_by_key(&port, |&(p, _)| p)
        .ok()
        .map(|at| SERVICES[at].1)
}

/// Every port with a known name, ascending.
pub fn named_ports() -> impl Iterator<Item = u16> {
    SERVICES.iter().map(|&(port, _)| port)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_is_sorted_unique_and_well_formed() {
        assert!(SERVICES.windows(2).all(|w| w[0].0 < w[1].0));
        for &(port, name) in SERVICES {
            assert!(port > 0);
            // Short lowercase identifiers, safe in every export format.
            assert!(!name.is_empty() && name.len() <= 20, "{port}");
            assert!(
                name.bytes()
                    .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-'),
                "{port}: {name}"
            );
        }
    }

    #[test]
    fn lookups() {
        assert_eq!(service_name(22), Some("ssh"));
        assert_eq!(service_name(3389), Some("rdp"));
        assert_eq!(service_name(445), Some("smb"));
        assert_eq!(service_name(8443), Some("https-alt"));
        assert_eq!(service_name(1), Some("tcpmux"));
        assert_eq!(service_name(62078), Some("iphone-sync"));
        assert_eq!(service_name(0), None);
        assert_eq!(service_name(1234), None);
        assert_eq!(service_name(65535), None);
    }

    #[test]
    fn names_of_the_old_service_probe_are_kept() {
        // Ports of the fixed probe list in `enrich::services`, as shown so far.
        for (port, name) in [
            (21, "ftp"),
            (22, "ssh"),
            (23, "telnet"),
            (80, "http"),
            (443, "https"),
            (445, "smb"),
            (3389, "rdp"),
            (8080, "http-alt"),
            (8443, "https-alt"),
        ] {
            assert_eq!(service_name(port), Some(name));
        }
    }
}
